/**
 * Project Documentation Runner
 * =============================
 *
 * AI runner that deeply reads a project's codebase and generates structured
 * documentation covering architecture, modules, APIs, data models, developer
 * guide, and tech stack.
 *
 * Uses `createSimpleClient()` with read-only tools (Read, Glob, Grep) and
 * streams progress back to the caller via an event callback.
 */

import { streamText, stepCountIs } from 'ai';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { mkdirSync } from 'node:fs';
import path from 'node:path';

import { createSimpleClient } from '../client/factory';
import { buildToolRegistry } from '../tools/build-registry';
import type { ToolContext } from '../tools/types';
import type { ModelShorthand, ThinkingLevel } from '../config/types';
import type { SecurityProfile } from '../security/bash-validator';
import { safeParseJson } from '../../utils/json-repair';
import { tryLoadPrompt } from '../prompts/prompt-loader';
import { AUTO_BUILD_PATHS } from '../../../shared/constants';

// =============================================================================
// Types
// =============================================================================

/** Structured project documentation generated by the AI runner */
export interface ProjectDocumentation {
  generatedAt: string;
  projectName: string;
  overview: string;
  architecture: string;
  modules: Array<{
    name: string;
    path: string;
    description: string;
    responsibilities: string[];
    keyFiles: string[];
  }>;
  apiSurface: string;
  dataModels: string;
  developerGuide: string;
  techStack: string;
}

/** Configuration for the project documentation runner */
export interface ProjectDocumentationConfig {
  /** Project directory path */
  projectDir: string;
  /** Model shorthand (defaults to 'sonnet') */
  modelShorthand?: ModelShorthand;
  /** Thinking level (defaults to 'medium') */
  thinkingLevel?: ThinkingLevel;
  /** Abort signal for cancellation */
  abortSignal?: AbortSignal;
}

/** Events emitted during documentation generation */
export type ProjectDocumentationEvent =
  | { type: 'text-delta'; delta: string }
  | { type: 'tool-use'; toolName: string; input: string }
  | { type: 'complete'; documentation: ProjectDocumentation }
  | { type: 'error'; error: string };

// =============================================================================
// Helpers
// =============================================================================

const DOCUMENTATION_TAG_OPEN = '<project_documentation>';
const DOCUMENTATION_TAG_CLOSE = '</project_documentation>';

/**
 * Extract the JSON content from `<project_documentation>...</project_documentation>` tags.
 */
function extractDocumentationBlock(text: string): string | null {
  const openIdx = text.indexOf(DOCUMENTATION_TAG_OPEN);
  const closeIdx = text.lastIndexOf(DOCUMENTATION_TAG_CLOSE);
  if (openIdx === -1 || closeIdx === -1 || closeIdx <= openIdx) return null;
  return text.slice(openIdx + DOCUMENTATION_TAG_OPEN.length, closeIdx).trim();
}

/**
 * Extract a brief description from tool call args for UI display.
 */
function extractToolInput(args: Record<string, unknown>): string {
  if (args.pattern) return `pattern: ${args.pattern}`;
  if (args.file_path) {
    const fp = String(args.file_path);
    return fp.length > 50 ? `...${fp.slice(-47)}` : fp;
  }
  if (args.path) return String(args.path);
  return '';
}

// =============================================================================
// Runner
// =============================================================================

/**
 * Run the project documentation AI runner with streaming.
 *
 * Emits `text-delta` and `tool-use` events while running, then a `complete`
 * event containing the parsed `ProjectDocumentation` object. Saves the result
 * to `AUTO_BUILD_PATHS.DOCUMENTATION_FILE` inside `config.projectDir`.
 *
 * @param config - Runner configuration
 * @param onEvent - Callback receiving streaming events
 */
export async function runProjectDocumentation(
  config: ProjectDocumentationConfig,
  onEvent: (event: ProjectDocumentationEvent) => void,
): Promise<void> {
  const {
    projectDir,
    modelShorthand = 'sonnet',
    thinkingLevel = 'medium',
    abortSignal,
  } = config;

  // Load system prompt from prompts directory; fall back to a minimal inline prompt
  const systemPrompt =
    tryLoadPrompt('project_documentation') ??
    `You are an expert software architect. Deeply read the codebase in "${projectDir}" using the available tools, then output comprehensive project documentation wrapped in <project_documentation> tags as a JSON object with keys: generatedAt, projectName, overview, architecture, modules, apiSurface, dataModels, developerGuide, techStack.`;

  const userPrompt =
    `Analyze the project at "${projectDir}" and generate comprehensive documentation. ` +
    `Start by reading .malvy/project_index.json, then explore READMEs, entry points, ` +
    `schemas, config files, and core source files. ` +
    `When done, output your findings wrapped in <project_documentation> tags as a JSON object.`;

  // Create tool context for read-only tools
  const toolContext: ToolContext = {
    cwd: projectDir,
    projectDir,
    specDir: join(projectDir, '.malvy', 'specs'),
    securityProfile: null as unknown as SecurityProfile,
    abortSignal,
  };

  // Bind read-only tools (insights agent set: Read, Glob, Grep)
  const registry = buildToolRegistry();
  const tools = registry.getToolsForAgent('insights', toolContext);

  // Create a simple streaming client
  const client = await createSimpleClient({
    systemPrompt,
    modelShorthand,
    thinkingLevel,
    maxSteps: 150,
    tools,
  });

  let fullText = '';

  try {
    const result = streamText({
      model: client.model,
      system: client.systemPrompt,
      prompt: userPrompt,
      tools: client.tools,
      stopWhen: stepCountIs(client.maxSteps),
      abortSignal,
    });

    for await (const part of result.fullStream) {
      switch (part.type) {
        case 'text-delta': {
          fullText += part.text;
          onEvent({ type: 'text-delta', delta: part.text });
          break;
        }
        case 'tool-call': {
          const args = 'input' in part ? (part.input as Record<string, unknown>) : {};
          const input = extractToolInput(args);
          onEvent({ type: 'tool-use', toolName: part.toolName, input });
          break;
        }
        case 'error': {
          const errorMsg = part.error instanceof Error ? part.error.message : String(part.error);
          onEvent({ type: 'error', error: errorMsg });
          break;
        }
        default:
          break;
      }
    }
  } catch (error) {
    const errorMsg = error instanceof Error ? error.message : String(error);
    onEvent({ type: 'error', error: errorMsg });
    return;
  }

  // Extract and parse the documentation block
  const jsonBlock = extractDocumentationBlock(fullText);
  if (!jsonBlock) {
    onEvent({ type: 'error', error: 'No <project_documentation> block found in AI response.' });
    return;
  }

  const documentation = safeParseJson<ProjectDocumentation>(jsonBlock);
  if (!documentation) {
    onEvent({ type: 'error', error: 'Failed to parse project documentation JSON.' });
    return;
  }

  // Persist to disk
  try {
    const outputPath = path.join(projectDir, AUTO_BUILD_PATHS.DOCUMENTATION_FILE);
    const outputDir = path.dirname(outputPath);
    mkdirSync(outputDir, { recursive: true });
    writeFileSync(outputPath, JSON.stringify(documentation, null, 2), 'utf-8');
  } catch (writeError) {
    // Emit an error but still emit complete — the caller has the data even if disk write fails
    const errorMsg = writeError instanceof Error ? writeError.message : String(writeError);
    onEvent({ type: 'error', error: `Failed to save documentation to disk: ${errorMsg}` });
  }

  onEvent({ type: 'complete', documentation });
}
